def _detect_lang_hint(code: str) -> str:
    """Return a markdown syntax-highlight hint from the code content."""
    if code.lstrip().startswith("//") and "func " in code:
        return "go"
    if code.lstrip().startswith("//") and ("fn " in code or "struct " in code):
        if "reqwest" in code or "tokio" in code or "impl " in code or "Mutex" in code:
            return "rust"
    if code.lstrip().startswith("#") or "def " in code or "class " in code:
        return "python"
    if "async function" in code or "class " in code and "Promise" in code:
        return "typescript"
    if "import {" in code or "new Agent" in code:
        return "typescript"
    if "func " in code:
        return "go"
    if "fn " in code:
        return "rust"
    return ""
