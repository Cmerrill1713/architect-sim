def generate_optimization_code(
    optimization_type: str,
    language: str,
    service_name: str = "",
    **kwargs,
) -> str:
    """Generate optimization code for a specific language.

    Args:
        optimization_type: One of ``OPTIMIZATION_TYPES``.
        language: One of ``SUPPORTED_LANGUAGES`` (aliases accepted).
        service_name: Inserted into the generated comment header.

    Returns:
        Ready-to-use source code string.

    Raises:
        ValueError: If *optimization_type* or *language* is unknown.
    """
    lang = _LANG_ALIASES.get(language.lower())
    if lang is None:
        raise ValueError(
            f"Unsupported language {language!r}. "
            f"Choose from: {', '.join(sorted(_LANG_ALIASES))}"
        )

    templates = TEMPLATES.get(optimization_type)
    if templates is None:
        raise ValueError(
            f"Unknown optimization type {optimization_type!r}. "
            f"Choose from: {', '.join(OPTIMIZATION_TYPES)}"
        )

    template = templates.get(lang)
    if template is None:
        raise ValueError(
            f"No {optimization_type!r} template for language {lang!r}"
        )

    return template.format(service_name=service_name or "unknown")


def generate_optimizations_for_service(
    bp: ServiceBlueprint,
    findings: list[Finding],
    llm_calls: Optional[list[LLMCall]] = None,
) -> list[tuple[str, str, str]]:
    """Generate all applicable optimization code for a service.

    Inspects *findings* and the blueprint to decide which optimizations to
    emit:

    * Resilience score below 30 pct  ->  retry wrapper + circuit breaker
    * Outbound calls without timeout  ->  timeout wrapper
    * Repeated identical outbound calls  ->  response cache
    * Raw ``http.Client`` / ``httpx`` without pool configuration  ->
      connection pool

    Returns:
        List of ``(optimization_type, code, description)`` tuples.
    """
    lang = _LANG_ALIASES.get(bp.language.lower(), bp.language.lower())
    if lang not in SUPPORTED_LANGUAGES:
        return []

    results: list[tuple[str, str, str]] = []

    # Categorize findings for this service.
    has_timeout_issue = False
    has_low_resilience = False
    seen_paths: dict[str, int] = {}  # path -> count of outbound calls

    for f in findings:
        if f.service != bp.name:
            continue
        if f.finding_type == "timeout_issue":
            has_timeout_issue = True
        if "resilience" in f.details.lower() or "retry" in f.details.lower():
            has_low_resilience = True

    # Check for repeated outbound paths (candidate for caching).
    for call in bp.outbound_calls:
        key = f"{call.method} {call.path}"
        seen_paths[key] = seen_paths.get(key, 0) + 1

    has_repeated_calls = any(v > 1 for v in seen_paths.values())

    # Check for missing retry config on outbound calls.
    calls_without_retry = [c for c in bp.outbound_calls if not c.retry_config]
    if calls_without_retry:
        has_low_resilience = True

    # Check for missing connection pool (heuristic: raw http usage).
    has_raw_client = not bp.retry_configs  # proxy for "no pool configured"

    # --- Emit applicable optimizations ---

    if has_low_resilience:
        code = generate_optimization_code("retry", lang, bp.name)
        results.append((
            "retry",
            code,
            f"Add retry wrapper with exponential backoff for {bp.name} "
            f"({len(calls_without_retry)} unprotected outbound calls)",
        ))

        code = generate_optimization_code("circuit_breaker", lang, bp.name)
        results.append((
            "circuit_breaker",
            code,
            f"Add circuit breaker to prevent {bp.name} from cascading "
            "failures when downstream services are down",
        ))

    if has_timeout_issue:
        code = generate_optimization_code("timeout", lang, bp.name)
        results.append((
            "timeout",
            code,
            f"Add explicit timeout wrapper for {bp.name} outbound HTTP calls",
        ))

    if has_repeated_calls:
        code = generate_optimization_code("response_cache", lang, bp.name)
        repeated = [p for p, c in seen_paths.items() if c > 1]
        results.append((
            "response_cache",
            code,
            f"Add response cache for {bp.name} repeated calls: "
            + ", ".join(repeated),
        ))

    if has_raw_client and bp.outbound_calls:
        code = generate_optimization_code("connection_pool", lang, bp.name)
        results.append((
            "connection_pool",
            code,
            f"Add connection pool for {bp.name} "
            f"({len(bp.outbound_calls)} outbound calls)",
        ))

    return results


def format_codegen_report(
    optimizations: dict[str, list[tuple[str, str, str]]],
) -> str:
    """Format generated code as a markdown report with copy-paste blocks.

    Args:
        optimizations: Mapping of ``service_name`` to the list returned by
            :func:`generate_optimizations_for_service`.

    Returns:
        Markdown string grouped by service.
    """
    if not optimizations:
        return "No optimization code generated.\n"

    total = sum(len(opts) for opts in optimizations.values())
    lines = [f"## Generated Optimization Code ({total} blocks)\n"]

    for service, opts in sorted(optimizations.items()):
        if not opts:
            continue
        lines.append(f"### {service}\n")
        for opt_type, code, description in opts:
            lines.append(f"**{opt_type.replace('_', ' ').title()}** -- {description}\n")
            # Detect language from the code content for syntax highlighting.
            lang_hint = _detect_lang_hint(code)
            lines.append(f"```{lang_hint}")
            lines.append(code.rstrip())
            lines.append("```\n")

    return "\n".join(lines)


