# Retry wrapper with exponential backoff.
# Generated by architect-sim for {service_name}.
import time
import httpx


def retry_request(
    method: str, url: str, max_attempts: int = 3, **kwargs
) -> httpx.Response:
    """Execute an HTTP request with exponential backoff retry."""
    delay = 0.2
    last_error: Exception | None = None
    for attempt in range(max_attempts):
        if attempt > 0:
            time.sleep(delay)
            delay = min(delay * 2, 5.0)
        try:
            resp = httpx.request(method, url, timeout=30.0, **kwargs)
            if resp.status_code < 500:
                return resp
        except httpx.RequestError as exc:
            last_error = exc
    raise last_error or Exception(f"Failed after {{max_attempts}} attempts")
