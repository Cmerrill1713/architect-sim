PY_CIRCUIT_BREAKER = '''\
# Circuit breaker to prevent cascading failures.
# Generated by architect-sim for {service_name}.
import threading
import time
from typing import Callable, TypeVar

T = TypeVar("T")


class CircuitBreaker:
    """Simple circuit breaker: closed -> open -> half-open -> closed."""

    def __init__(self, threshold: int = 5, reset_timeout: float = 30.0) -> None:
        self._lock = threading.Lock()
        self._failures = 0
        self._threshold = threshold
        self._state = "closed"
        self._last_failure = 0.0
        self._reset_timeout = reset_timeout

    def call(self, fn: Callable[[], T]) -> T:
        with self._lock:
            if self._state == "open":
                if time.monotonic() - self._last_failure > self._reset_timeout:
                    self._state = "half-open"
                else:
                    raise RuntimeError("circuit breaker open")

        try:
            result = fn()
        except Exception:
            with self._lock:
                self._failures += 1
                self._last_failure = time.monotonic()
                if self._failures >= self._threshold:
                    self._state = "open"
            raise

        with self._lock:
            self._failures = 0
            self._state = "closed"
        return result
'''

