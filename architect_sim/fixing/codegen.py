RUST_CIRCUIT_BREAKER = '''\
// Circuit breaker to prevent cascading failures.
// Generated by architect-sim for {service_name}.
use std::sync::Mutex;
use std::time::{{Duration, Instant}};

struct CircuitBreaker {{
    failures: Mutex<CircuitState>,
    threshold: u32,
    reset_timeout: Duration,
}}

struct CircuitState {{
    count: u32,
    state: BreakerState,
    last_failure: Option<Instant>,
}}

#[derive(PartialEq)]
enum BreakerState {{
    Closed,
    Open,
    HalfOpen,
}}

impl CircuitBreaker {{
    fn new(threshold: u32, reset_timeout: Duration) -> Self {{
        Self {{
            failures: Mutex::new(CircuitState {{
                count: 0,
                state: BreakerState::Closed,
                last_failure: None,
            }}),
            threshold,
            reset_timeout,
        }}
    }}

    fn call<F, T, E>(&self, f: F) -> Result<T, E>
    where
        F: FnOnce() -> Result<T, E>,
        E: From<std::io::Error>,
    {{
        {{
            let mut s = self.failures.lock().unwrap();
            if s.state == BreakerState::Open {{
                if s.last_failure.map_or(false, |t| t.elapsed() > self.reset_timeout) {{
                    s.state = BreakerState::HalfOpen;
                }} else {{
                    return Err(E::from(std::io::Error::new(
                        std::io::ErrorKind::ConnectionRefused,
                        "circuit breaker open",
                    )));
                }}
            }}
        }}
        match f() {{
            Ok(val) => {{
                let mut s = self.failures.lock().unwrap();
                s.count = 0;
                s.state = BreakerState::Closed;
                Ok(val)
            }}
            Err(e) => {{
                let mut s = self.failures.lock().unwrap();
                s.count += 1;
                s.last_failure = Some(Instant::now());
                if s.count >= self.threshold {{
                    s.state = BreakerState::Open;
                }}
                Err(e)
            }}
        }}
    }}
}}
'''

